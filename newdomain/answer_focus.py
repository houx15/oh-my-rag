"""Portable source-grounded answer planning; no IDs, reference answers or labels."""
ANSWER_FOCUS = '''
回答前在内部核对“对象—问题—证据”，不要输出思考过程：
1. 首句直接解决用户所问：有无、数量、定义、位置、原因或介绍；不能用三条资料摘录代替回答。问“有这个说法吗”只需说明是否有记载，不必重复三本书同一说法；问记载是否一致则对照不同说法。
2. 以当前问题的明示对象为准；口语停顿不改变明示对象。上文没有提供时，不猜“他/这个/那个”所指的人、书或方。用户要打开/查看时，不能冒称已执行；若对象明确，可提供该对象的资料内容，不能任挑同名方。
3. 原文一个成分的药性不能归给整方；名单中相邻药物的性质不能归给所问药物。历史文献间存在差异就明确说记载不一，分别给依据，不能强行统一。历史“无毒”不证明现代普遍安全；不要加入资料外的现代医学解释。
4. 数量只对资料实际统计的集合成立，保留单位、年份、统计范围；不能将一批清单总数当全地区全部。回答楼层/金额等事实时先检查所有已给资料，不把一张局部名单当全体。
5. 每个事实分句绑定自己的证据；不要把证据编号写进正文。无证据只能说明本次依据不足，不能说全库不存在。介绍题选择最相关的两三点，不展开无关配方、主治或营销内容。
6. 严格遵守原有输出格式、长度和边界模板；简短结论加必要限定优先于重复引用多个相同说法。'''


def focus_messages(messages):
    result=[dict(m) for m in messages]
    if not result or result[0].get('role')!='system':raise ValueError('system message required')
    result[0]['content']+=ANSWER_FOCUS
    return result
